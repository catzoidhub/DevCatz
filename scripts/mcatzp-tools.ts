// bun --tsconfig-override=tsconfig.node.json scripts/mcatzp-tools.ts — writes DevCatz's MCatzP tools as Markdown, from the
// registry itself, so the reference never drifts (MCatzP #23, Catzoid #85). Runs nothing: only names, tiers and inputs.
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { plugin } from 'bun';
import type { HerdApi } from '@shared/types';
import type { Scopes } from '../src/main/mcatzp/actions';

// A throwaway folder: importing the store must not read or write the real settings.
const scratch = mkdtempSync(join(tmpdir(), 'devcatz-tools-'));
// The registry's modules import Electron for other things: a stand-in, since only definitions are read here.
const stub = (): unknown => new Proxy(function () {}, { get: (_t, k) => (k === Symbol.toPrimitive ? () => '' : stub()), apply: () => stub(), construct: () => stub() as object });
plugin({
  name: 'electron-stub',
  setup(b) {
    b.module('electron', () => ({ exports: { ...Object.fromEntries(['app', 'BrowserWindow', 'clipboard', 'crashReporter', 'dialog', 'ipcMain', 'Menu', 'nativeImage', 'nativeTheme', 'net', 'Notification', 'powerMonitor', 'protocol', 'safeStorage', 'screen', 'session', 'shell', 'systemPreferences', 'Tray', 'utilityProcess', 'webContents'].map((k) => [k, stub()])), app: new Proxy({ getPath: () => scratch, getVersion: () => '0', isPackaged: false, getName: () => 'DevCatz' }, { get: (t, k) => (t as Record<string | symbol, unknown>)[k] ?? stub() }) }, loader: 'object' }));
  },
});
const { changeActions, readActions } = await import('../src/main/mcatzp/actions');
const { destructiveActions } = await import('../src/main/mcatzp/destructive');
const { devChanges } = await import('../src/main/mcatzp/devchanges');
const { moreReads } = await import('../src/main/mcatzp/reads');
const { serviceChanges } = await import('../src/main/mcatzp/servicechanges');
const { siteChanges } = await import('../src/main/mcatzp/sitechanges');
const { windowChanges, windowReads } = await import('../src/main/mcatzp/windowactions');

const OUT = resolve(import.meta.dir, '../../MCatzP/docs/tools/devcatz.md');
const TIER = { read: 'Read: runs at once, inside what is shared', change: 'Change: asks in DevCatz first', destructive: 'Destructive: you type a name in DevCatz, every time' } as const;

// Everything shared and on, so every tool is listed. The API is never called: only the definitions are read.
const api = {} as HerdApi;
const scopes: Scopes = { site: () => true, services: true, changes: true, messages: true, allSites: true, secretName: () => false };
const all = [
  ...readActions(api, scopes),
  ...moreReads(api, scopes),
  ...windowReads(api, scopes),
  ...changeActions(api, scopes),
  ...devChanges(api, scopes),
  ...siteChanges(api, scopes),
  ...serviceChanges(api, scopes),
  ...destructiveActions(api, scopes),
  ...windowChanges(api, scopes),
];

type Schema = { properties?: Record<string, { description?: string; enum?: string[]; type?: string | string[] }>; required?: string[] };
const inputs = (s?: Schema) => {
  const entries = Object.entries(s?.properties ?? {});
  if (!entries.length) return 'None.';
  return entries.map(([k, v]) => `\`${k}\`${s?.required?.includes(k) ? '' : ' (optional)'}${v.enum ? `: one of ${v.enum.join(', ')}` : v.description ? `: ${v.description}` : ''}`).join('; ');
};
const cell = (t: string) => t.replace(/\|/g, '\\|').replace(/\n/g, ' ');

let md = `# DevCatz tools\n\nGenerated by DevCatz's \`scripts/mcatzp-tools.ts\`: do not edit by hand. A client sees each one as \`devcatz_<name>\`, and only those that Settings → MCatzP shares: mail, SMS and WhatsApp content is off at first, and "Let clients ask for changes" off leaves only the read tools.\n`;
for (const tier of ['read', 'change', 'destructive'] as const) {
  const list = all.filter((a) => a.tier === tier);
  md += `\n## ${TIER[tier]} (${list.length})\n\n| Tool | What it does | Inputs |\n|---|---|---|\n`;
  for (const a of list) md += `| \`${a.name}\` | ${cell(a.description)} | ${cell(inputs(a.input as Schema))} |\n`;
}
writeFileSync(OUT, md);
console.log(`${all.length} tools → ${OUT}`);
rmSync(scratch, { recursive: true, force: true });
process.exit(0);
