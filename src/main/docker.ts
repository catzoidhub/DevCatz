/** `docker compose ps` for the file, with OrbStack URLs. */
export async function services(root: string, file: string, project: string | null): Promise<DockerService[]> {
  const args = [...cli.compose, '-f', file, ...(project ? ['-p', project] : []), 'ps', '-a', '--format', 'json'];
  const r = await run(cli.bin, args, { cwd: root, timeout: 10_000 });
  if (r.code !== 0) return [];
  const rows = r.stdout
    .trim()
    .split('\n')
    .filter(Boolean)
    .flatMap((l) => {
      try {
        const v = JSON.parse(l);
        return Array.isArray(v) ? v : [v];
      } catch {
        return [];
      }
    }) as { Service: string; State: string; Status: string; Project: string; Health?: string; Publishers?: { PublishedPort: number; TargetPort: number }[] }[];
  // Workers, schedulers and data services have no web page to open.
  const NOT_HTTP = /worker|scheduler|queue|cron|horizon|db|redis|postgres|mysql|mariadb|mongo|valkey|memcache/;
  return rows.map((s) => ({
    service: s.Service,
    state: s.State,
    status: s.Status,
    health: s.Health || null,
    url: !(s.Publishers ?? []).some((x) => x.PublishedPort) && NOT_HTTP.test(s.Service)
      ? null
      : orbLocal
      ? `https://${s.Service}.${s.Project}.orb.local`
      : (s.Publishers ?? []).find((x) => x.PublishedPort)
        ? `http://localhost:${(s.Publishers ?? []).find((x) => x.PublishedPort)!.PublishedPort}`
        : null,
    published: (s.Publishers ?? []).filter((x) => x.PublishedPort).map((x) => `${x.PublishedPort}→${x.TargetPort}`),
  }));
}

/** Runs a compose command, streaming its output line by line. */
export function compose(
  root: string,
  file: string,
  project: string | null,
  args: string[],
  onLine: (stream: 'out' | 'err', text: string) => void,
): Promise<number> {
  return new Promise((resolve) => {
    const child = spawn(cli.bin, [...cli.compose, '-f', file, ...(project ? ['-p', project] : []), ...args], {
      cwd: root,
      env: { ...getShellEnv(), COMPOSE_PROGRESS: 'plain', BUILDKIT_PROGRESS: 'plain', COMPOSE_ANSI: 'never' },
      stdio: ['ignore', 'pipe', 'pipe'],
    });
    const pipe = (stream: 'out' | 'err') => {
      let rest = '';
      return (d: Buffer) => {
        const parts = (rest + d.toString()).split(/\r?\n/);
        rest = parts.pop() ?? '';
        for (const l of parts) if (l.trim()) onLine(stream, l);
      };
    };
    child.stdout.on('data', pipe('out'));
    // Compose writes its progress to stderr; that is not an error.
    child.stderr.on('data', pipe('out'));
    child.on('error', (e) => {
      onLine('err', e.message);
      resolve(1);
    });
    child.on('close', (code) => resolve(code ?? 1));
  });
}
