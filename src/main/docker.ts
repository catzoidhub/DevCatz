interface Ctx {
  opts: DockerGenOptions;
  p: ProjectConfig;
  stack: StackInfo;
  env: Record<string, string>;
  phpVersion: string | null;
  goVersion: string | null;
  pythonVersion: string | null;
  nodeMajor: number;
}

const INTERNAL_PORT: Record<string, number> = { go: 8080, laravel: 8080, php: 8080, django: 8000, flask: 8000, fastapi: 8000, litestar: 8000, python: 8000 };
const STATIC = new Set(['vite-vue', 'vite-react', 'vite', 'astro']);
const portOf = (a: AppInfo) => (STATIC.has(a.framework) ? 80 : (INTERNAL_PORT[a.framework] ?? 3000));

/** Services that become containers (the Vite dev server of a Laravel site is built into its image instead). */
const servedApps = (s: StackInfo) => s.apps.filter((a) => a.kind !== 'assets');

function serviceName(a: AppInfo, s: StackInfo): string {
  const apps = servedApps(s);
  if (apps.length === 1) return 'app';
  return slugify(a.dir === '.' ? a.name : posix.basename(a.dir));
}

/** Lockfile-exact install when there is a lockfile. */
function installCmd(pm: string, root: string): string {
  const has = (f: string) => existsSync(join(root, f));
  if (pm === 'bun') return has('bun.lock') || has('bun.lockb') ? 'bun install --frozen-lockfile' : 'bun install';
  if (pm === 'pnpm') return has('pnpm-lock.yaml') ? 'pnpm install --frozen-lockfile' : 'pnpm install';
  if (pm === 'yarn') return has('yarn.lock') ? 'yarn install --frozen-lockfile' : 'yarn install';
  return has('package-lock.json') ? 'npm ci' : 'npm install';
}

function jsBase(ctx: Ctx, pm: string): string[] {
  if (pm === 'bun') return ['FROM oven/bun:1 AS base', 'WORKDIR /app'];
  return [
    `FROM node:${ctx.nodeMajor}-alpine AS base`,
    // Native bindings of Tailwind v4 (oxide) and lightningcss need glibc shims on musl.
    'RUN apk add --no-cache libc6-compat',
    'WORKDIR /app',
    ...(pm === 'pnpm' || pm === 'yarn' ? ['RUN corepack enable'] : []),
  ];
}

function lockfiles(root: string): string[] {
  return ['package.json', 'package-lock.json', 'pnpm-lock.yaml', 'pnpm-workspace.yaml', 'yarn.lock', 'bun.lock', 'bun.lockb', '.npmrc'].filter((f) =>
    existsSync(join(root, f)),
  );
}

/** The app's own `build` script, else the framework's CLI (a demo without scripts still builds). */
function buildCmd(a: AppInfo, pkg: PackageJson | null, pm: string): string {
  if (pkg?.scripts?.build) return `${pm === 'npm' ? 'npm run' : `${pm} run`} build`;
  const x = pm === 'bun' ? 'bunx' : 'npx';
  const cli: Partial<Record<AppInfo['framework'], string>> = {
    nuxt: 'nuxt build', next: 'next build', astro: 'astro build', sveltekit: 'vite build', nestjs: 'nest build',
    vite: 'vite build', 'vite-vue': 'vite build', 'vite-react': 'vite build', 'tanstack-start': 'vite build',
  };
  return cli[a.framework] ? `${x} ${cli[a.framework]}` : 'true # no build step';
}

function jsDockerfile(ctx: Ctx, a: AppInfo): string {
  const { stack, p } = ctx;
  const pm = stack.packageManager ?? 'npm';
  const runPm = pm === 'npm' ? 'npm run' : `${pm} run`;
  const exec = pm === 'bun' ? 'bun' : 'node';
  const appDir = a.dir === '.' ? '/app' : `/app/${a.dir}`;
  const pkg = readJson<PackageJson>(join(p.path, a.dir, 'package.json'));
  const libs = stack.libs.filter((l) => l.build);
  const port = portOf(a);
  const lines = [
    GENERATED_MARK + ` for ${a.name} (${a.framework}). Build context: the project root.`,
    ...jsBase(ctx, pm),
    '',
    'FROM base AS build',
    // Whole repo: workspaces need their sibling packages to install and build.
    stack.monorepo ? 'COPY . .' : `COPY ${lockfiles(p.path).join(' ')} ./`,
    `RUN ${installCmd(pm, ctx.p.path)}`,
    ...(stack.monorepo ? [] : ['COPY . .']),
    // `prisma generate` needs no connection, but prisma.config.ts may read DATABASE_URL.
    ...(a.prisma || stack.prismaDir
      ? [`RUN cd /app/${stack.prismaDir ?? a.dir} && DATABASE_URL=postgresql://build:build@localhost:5432/build ${pm === 'bun' ? 'bunx' : 'npx'} prisma generate`]
      : []),
    ...libs.map((l) => `RUN cd /app/${l.dir} && ${runPm} build`),
    ...(ctx.opts.mrcatzDatatable && a.framework === 'nuxt'
      ? [
          '# MrCatz DataTable: Tailwind scans node_modules/@mrcatz/datatable-vue/dist (installed above) via @source.',
          `RUN cd ${appDir} && ${pm === 'bun' ? 'bunx' : 'npx'} nuxt prepare`,
        ]
      : []),
    `RUN cd ${appDir} && ${buildCmd(a, pkg, pm)}`,
    '',
  ];
  if (STATIC.has(a.framework)) {
    lines.push(
      'FROM nginx:1.27-alpine',
      `COPY --from=build ${appDir}/dist /usr/share/nginx/html`,
      // SPA fallback: unknown paths load index.html.
      `RUN printf 'server { listen 80; root /usr/share/nginx/html; location / { try_files $uri $uri/ /index.html; } }' > /etc/nginx/conf.d/default.conf`,
      'EXPOSE 80',
    );
    return lines.join('\n') + '\n';
  }
  lines.push('FROM base AS runtime', 'ENV NODE_ENV=production', `ENV PORT=${port} HOST=0.0.0.0 NITRO_HOST=0.0.0.0 NITRO_PORT=${port}`);
  if (a.framework === 'nuxt') {
    lines.push(`COPY --from=build ${appDir}/.output /app/.output`, 'WORKDIR /app', `CMD ["${exec}", ".output/server/index.mjs"]`);
  } else if (a.framework === 'tanstack-start' && !pkg?.scripts?.start) {
    // vite build → dist/server/server.js (a fetch handler) + dist/client; srvx serves both (TanStack's own advice).
    lines.push('COPY --from=build /app /app', `WORKDIR ${appDir}`, `CMD ["npx", "-y", "srvx", "--prod", "-s", "dist/client", "dist/server/server.js"]`);
  } else if (a.framework === 'sveltekit') {
    lines.push(`COPY --from=build ${appDir}/build /app/build`, `COPY --from=build ${appDir}/package.json /app/`, 'WORKDIR /app', `CMD ["${exec}", "build"]`);
  } else {
    // Next, NestJS, Express, …: keep the installed tree and run the app's own start script.
    const start = pkg?.scripts?.['start:prod'] ? 'start:prod' : pkg?.scripts?.start ? 'start' : null;
    const main = a.framework === 'nestjs' ? 'dist/main' : (pkg as { main?: string } | null)?.main ?? 'index.js';
    lines.push('COPY --from=build /app /app', `WORKDIR ${appDir}`);
    if (a.prisma || stack.prismaDir) lines.push(`# Applies pending migrations, then starts the server.`);
    const migrate = a.prisma || stack.prismaDir ? `cd /app/${stack.prismaDir ?? a.dir} && ${pm === 'bun' ? 'bunx' : 'npx'} prisma migrate deploy && cd ${appDir} && ` : '';
    const run = start ? `${runPm} ${start}` : `${exec} ${main}`;
    lines.push(migrate ? `CMD ["sh", "-c", "${migrate}${run}"]` : `CMD ${JSON.stringify(run.split(' '))}`);
  }
  lines.push(`EXPOSE ${port}`);
  return lines.join('\n') + '\n';
}

/**
 * Python: python:<x.y>-slim with uv (copied from its image), dependencies from
 * uv.lock / pyproject or requirements.txt, then the production server:
 * gunicorn for Django / Flask (WSGI), uvicorn for FastAPI and other ASGI apps.
 */
function pythonDockerfile(ctx: Ctx, a: AppInfo): string {
  const v = ctx.pythonVersion?.split('.').slice(0, 2).join('.') ?? '3.13';
  const root = ctx.p.path;
  const has = (f: string) => existsSync(join(root, f));
  const req = ['requirements.txt', 'requirements/base.txt', 'requirements/production.txt'].find(has);
  const pyproject = has('pyproject.toml') && /^\s*dependencies\s*=/m.test(readFileSync(join(root, 'pyproject.toml'), 'utf8'));
  const port = portOf(a);
  // Production command from the dev one: module paths stay, reload / debug flags go.
  const dev = a.command ?? '';
  const asgi = dev.match(/uvicorn (\S+)/)?.[1] ?? dev.match(/--app (\S+)/)?.[1];
  let cmd: string;
  if (a.framework === 'django') {
    const settingsPkg = readdirSync(root).find((d) => existsSync(join(root, d, 'wsgi.py')));
    cmd = settingsPkg ? `gunicorn ${settingsPkg}.wsgi:application --bind 0.0.0.0:${port} --workers 3` : `python manage.py runserver 0.0.0.0:${port}`;
  } else if (a.framework === 'flask') cmd = `gunicorn '${asgi ?? 'app:app'}' --bind 0.0.0.0:${port} --workers 3`;
  else if (a.framework === 'litestar') cmd = `litestar --app ${asgi ?? 'app:app'} run --host 0.0.0.0 --port ${port}`;
  else if (asgi) cmd = `uvicorn ${asgi} --host 0.0.0.0 --port ${port} --proxy-headers`;
  else cmd = dev.replace(/\$\{PORT[^}]*\}/g, String(port));
  return [
    GENERATED_MARK + ` for ${a.name} (Python ${v}). Build context: the project root.`,
    `FROM python:${v}-slim`,
    'COPY --from=ghcr.io/astral-sh/uv:latest /uv /uvx /usr/local/bin/',
    'WORKDIR /app',
    'ENV PYTHONUNBUFFERED=1 PYTHONDONTWRITEBYTECODE=1 UV_COMPILE_BYTECODE=1 UV_LINK_MODE=copy',
    ...(pyproject
      ? [
          '# Dependencies first (cached until the lockfile changes).',
          `COPY pyproject.toml ${has('uv.lock') ? 'uv.lock ' : ''}./`,
          `RUN uv sync ${has('uv.lock') ? '--frozen ' : ''}--no-dev --no-install-project`,
          'ENV PATH="/app/.venv/bin:$PATH"',
        ]
      : req
        ? [`COPY ${req} ./requirements.txt`, 'RUN uv pip install --system -r requirements.txt']
        : []),
    // gunicorn / uvicorn when the project does not depend on them.
    `RUN ${pyproject ? 'uv pip install --python /app/.venv/bin/python' : 'uv pip install --system'} ${a.framework === 'django' || a.framework === 'flask' ? 'gunicorn' : 'uvicorn'} || true`,
    'COPY . .',
    ...(pyproject ? ['RUN uv sync ' + (has('uv.lock') ? '--frozen ' : '') + '--no-dev'] : []),
    ...(a.framework === 'django' ? ['RUN python manage.py collectstatic --noinput || true'] : []),
    `EXPOSE ${port}`,
    `CMD ${JSON.stringify(['sh', '-c', cmd])}`,
    '',
  ].join('\n');
}

/** A Go module's `replace … => ../path` directives that point at a local checkout (outside the build context). */
export function goLocalReplaces(modDir: string): { name: string; rel: string }[] {
  const mod = readText(join(modDir, 'go.mod')) ?? '';
  const lines = [...mod.matchAll(/^\s*replace\s+(.+)$/gm), ...[...mod.matchAll(/^replace\s*\(([^)]*)\)/gms)].flatMap((m) => [...m[1].matchAll(/^\s*(.+)$/gm)])];
  const out: { name: string; rel: string }[] = [];
  for (const l of lines) {
    const target = l[1].split('=>')[1]?.trim().split(/\s+/)[0];
    if (target && target.startsWith('../')) out.push({ name: `gomod-${slugify(posix.basename(target))}`, rel: target });
  }
  return out;
}

/** The commands a Go module builds (`cmd/<name>/main.go`), and the one that serves (the dev command's, else api / server). */
function goCommands(modDir: string, a: AppInfo): { all: string[]; server: string | null } {
  const cmdDir = join(modDir, 'cmd');
  const all = existsSync(cmdDir) ? readdirSync(cmdDir).filter((d) => existsSync(join(cmdDir, d, 'main.go'))) : [];
  const fromDev = a.command?.match(/go run \.\/cmd\/([\w-]+)/)?.[1];
  const server = fromDev && all.includes(fromDev) ? fromDev : (['api', 'server', 'app', 'web'].find((n) => all.includes(n)) ?? null);
  return { all, server };
}

/**
 * Go (the MrCatz DataTable Go pattern, https://datatable.catzoid.tech/docs/deployment/docker): modules downloaded in
 * their own cached layer, static binaries (CGO_ENABLED=0) for every command in ./cmd (api, and e.g. migrate / seed),
 * then only those binaries in a small Alpine image as a non-root user. A `migrate` command that takes `up` runs
 * before the API; an uploads/ folder is created for the user (a volume in compose). Local `replace` directives
 * come in as extra build contexts (compose `additional_contexts`).
 */
function goDockerfile(ctx: Ctx, a: AppInfo): string {
  const v = ctx.goVersion?.split('.').slice(0, 2).join('.') ?? '1';
  const dir = a.dir === '.' ? '.' : a.dir;
  const modDir = join(ctx.p.path, dir);
  const at = (f: string) => (dir === '.' ? f : `${dir}/${f}`);
  const goMod = readText(join(modDir, 'go.mod')) ?? '';
  const { all, server } = goCommands(modDir, a);
  const many = all.length > 1 && server;
  const migrate = all.includes('migrate') && /"up"/.test(readText(join(modDir, 'cmd/migrate/main.go')) ?? '');
  const uploads = existsSync(join(modDir, 'uploads'));
  const replaces = goLocalReplaces(modDir);
  const bin = many ? server : 'app';
  const pkg = a.command?.match(/go run (\.\/[\w./-]+)/)?.[1] ?? (server ? `./cmd/${server}` : '.');
  const cache = '--mount=type=cache,target=/go/pkg/mod';
  const portEnv = [...new Set(['PORT', ...a.portVars])].map((x) => `${x}=8080`).join(' ');
  return [
    GENERATED_MARK + ` for ${a.name} (Go). Build context: the project root.`,
    ...(ctx.opts.mrcatzDatatable ? ['# MrCatz DataTable: see https://datatable.catzoid.tech/docs/deployment/docker'] : []),
    `FROM golang:${v}-alpine AS build`,
    'WORKDIR /src',
    ...replaces.map((r) => `# go.mod: replace => ${r.rel} (a local checkout, passed in as the "${r.name}" build context)\nCOPY --from=${r.name} . ${posix.resolve('/src', r.rel)}`),
    '# Modules first: cached until go.mod / go.sum change.',
    `COPY ${[at('go.mod'), ...(existsSync(join(modDir, 'go.sum')) ? [at('go.sum')] : [])].join(' ')} ./`,
    `RUN ${cache} go mod download`,
    `COPY ${dir === '.' ? '.' : dir} ./`,
    many
      ? `# Static binaries for every command in ./cmd (${all.join(', ')}).\nRUN ${cache} --mount=type=cache,target=/root/.cache/go-build \\\n    CGO_ENABLED=0 go build -trimpath -ldflags="-s -w" -o /out/ ./cmd/...`
      : `RUN ${cache} --mount=type=cache,target=/root/.cache/go-build \\\n    CGO_ENABLED=0 go build -trimpath -ldflags="-s -w" -o /out/app ${pkg}`,
    '',
    '# Runtime: just the binaries, as a non-root user.',
    'FROM alpine:3.22',
    'RUN apk add --no-cache ca-certificates tzdata && addgroup -S app && adduser -S app -G app',
    'WORKDIR /app',
    'COPY --from=build /out/ /usr/local/bin/',
    ...(uploads ? ['RUN mkdir -p uploads && chown -R app:app uploads'] : []),
    'USER app',
    `ENV ${/gin-gonic\/gin/.test(goMod) ? 'GIN_MODE=release ' : ''}${portEnv}`,
    'EXPOSE 8080',
    migrate ? `# Applies pending migrations, then starts the API.\nCMD ["sh", "-c", "migrate up && exec ${bin}"]` : `CMD ["${bin}"]`,
    '',
  ].join('\n');
}

/** Extensions serversideup/php images already have. */
const SERVERSIDEUP_EXTS = new Set(['ctype', 'curl', 'dom', 'fileinfo', 'filter', 'hash', 'json', 'mbstring', 'mysqli', 'opcache', 'openssl', 'pcntl', 'pcre', 'pdo', 'pdo_mysql', 'pdo_pgsql', 'pdo_sqlite', 'redis', 'session', 'sodium', 'tokenizer', 'xml', 'zip', 'simplexml', 'xmlreader', 'xmlwriter', 'libxml', 'iconv', 'posix', 'sqlite3']);
/** What mrcatz/datatable needs on top (exports, image handling, numbers, locale). */
const MRCATZ_EXTS = ['intl', 'gd', 'bcmath', 'exif'];
/** Blade views MrCatz DataTable's Tailwind @source lines point at. */
const MRCATZ_VENDOR = ['vendor/mrcatz', 'vendor/laravel/framework/src/Illuminate/Pagination'];

interface ComposerFile {
  require?: Record<string, string>;
}

export function usesMrcatz(root: string, stack: StackInfo): boolean {
  const composer = readJson<ComposerFile>(join(root, 'composer.json'));
  if (Object.keys(composer?.require ?? {}).some((k) => k.startsWith('mrcatz/'))) return true;
  const dirs = new Set(['.', ...stack.apps.map((a) => a.dir)]);
  if ([...dirs].some((d) => /github\.com\/mrc4tz\/mrcatz-go-datatables?\b/.test(readText(join(root, d, 'go.mod')) ?? ''))) return true;
  return [...dirs].some((d) => {
    const pkg = readJson<PackageJson>(join(root, d, 'package.json'));
    return Object.keys({ ...pkg?.dependencies, ...pkg?.devDependencies }).some((k) => k.startsWith('@mrcatz/datatable'));
  });
}

/**
 * Vendor folders Tailwind scans (`@source '../../vendor/…'` in resources/css):
 * vendor/ is not in the build context, so the assets stage copies them from
 * the Composer stage, or classes used only there are dropped.
 */
function tailwindVendorSources(root: string): string[] {
  const out = new Set<string>();
  let files: string[] = [];
  try {
    files = readdirSync(join(root, 'resources/css')).filter((f) => f.endsWith('.css'));
  } catch {
    return [];
  }
  for (const f of files) {
    const text = readText(join(root, 'resources/css', f)) ?? '';
    for (const m of text.matchAll(/@source\s+['"](?:\.\.\/)+(vendor\/[^'"]+)['"]/g)) {
      const parts: string[] = [];
      for (const seg of m[1].split('/')) {
        if (/[*{]/.test(seg) || /\.\w+$/.test(seg)) break;
        parts.push(seg);
      }
      if (parts.length >= 2) out.add(parts.join('/'));
    }
  }
  return [...out];
}

/**
 * Packages `composer install --no-dev` puts in vendor/ (composer.lock, else
 * composer.json). A COPY of a vendor path nobody installs fails the build.
 */
function installedPackages(root: string): Set<string> {
  const lock = readJson<{ packages?: { name: string }[] }>(join(root, 'composer.lock'));
  if (lock?.packages) return new Set(lock.packages.map((p) => p.name.toLowerCase()));
  return new Set(Object.keys(readJson<ComposerFile>(join(root, 'composer.json'))?.require ?? {}).map((k) => k.toLowerCase()));
}

/** vendor/mrcatz → any mrcatz/* package; vendor/a/b/… → package a/b. */
function vendorPathInstalled(path: string, pkgs: Set<string>): boolean {
  const [, vendor, name] = path.split('/');
  if (!name) return [...pkgs].some((p) => p.startsWith(`${vendor}/`));
  return pkgs.has(`${vendor}/${name}`.toLowerCase());
}

export function mrcatzInstalled(root: string): boolean {
  return [...installedPackages(root)].some((p) => p.startsWith('mrcatz/'));
}

/** Keep only top-most paths (vendor/mrcatz covers vendor/mrcatz/x/views). */
const topMost = (paths: string[]) => [...new Set(paths)].filter((p, _, all) => !all.some((o) => o !== p && p.startsWith(`${o}/`))).sort();

export function usesOctane(root: string): boolean {
  return Boolean(readJson<ComposerFile>(join(root, 'composer.json'))?.require?.['laravel/octane']);
}

function phpDockerfile(ctx: Ctx, a: AppInfo): string {
  const root = ctx.p.path;
  const minor = ctx.phpVersion?.split('.').slice(0, 2).join('.') ?? '8.4';
  const pm = ctx.stack.packageManager ?? 'npm';
  const pkg = readJson<PackageJson>(join(root, 'package.json'));
  const assets = Boolean(pkg?.scripts?.build);
  // Laravel Mix writes into public/ (css, js, mix-manifest.json); Vite into public/build.
  const mix = Boolean({ ...pkg?.dependencies, ...pkg?.devDependencies }['laravel-mix']);
  const mrcatz = ctx.opts.mrcatzDatatable;
  const octane = usesOctane(root);
  // Laravel always runs on FrankenPHP (with Octane when installed); plain PHP on nginx + PHP-FPM.
  const laravel = a.framework === 'laravel';
  const pkgs = installedPackages(root);
  const vendorPaths = topMost([...tailwindVendorSources(root), ...(mrcatz ? MRCATZ_VENDOR : [])]).filter((v) => vendorPathInstalled(v, pkgs));
  const composer = readJson<ComposerFile>(join(root, 'composer.json'));
  const exts = [
    ...new Set([
      ...Object.keys(composer?.require ?? {})
        .filter((k) => k.startsWith('ext-'))
        .map((k) => k.slice(4).toLowerCase()),
      ...(mrcatz ? MRCATZ_EXTS : []),
    ]),
  ].filter((e) => !SERVERSIDEUP_EXTS.has(e));
  const alpine = pm !== 'bun';
  return [
    GENERATED_MARK +
      ` for ${a.name} (${laravel ? 'Laravel' : 'PHP'}): ${octane ? 'Octane on FrankenPHP' : laravel ? 'FrankenPHP' : 'nginx + PHP-FPM'} (serversideup/php).`,
    ...(laravel && !octane ? ['# Tip: `composer require laravel/octane` and regenerate for Octane worker mode (octane:start).'] : []),
    ...(mrcatz ? ['# MrCatz DataTable: see https://datatable.catzoid.tech/docs/deployment/docker'] : []),
    '',
    '# Stage 1: Composer dependencies (Linux vendor/, never the host one)',
    'FROM composer:2 AS vendor',
    'WORKDIR /app',
    'COPY composer.json composer.lock* ./',
    // The composer image lacks the app's PHP extensions; the runtime image has them.
    'RUN composer install --no-dev --no-interaction --no-scripts --no-autoloader --prefer-dist --ignore-platform-reqs',
    'COPY . .',
    // No scripts: package discovery happens on first boot (bootstrap/cache is not in the image).
    'RUN composer dump-autoload --optimize --no-dev --no-scripts',
    '',
    ...(assets
      ? [
          '# Stage 2: build assets',
          `FROM ${pm === 'bun' ? 'oven/bun:1' : `node:${ctx.nodeMajor}-alpine`} AS assets`,
          ...(alpine ? ['RUN apk add --no-cache libc6-compat'] : []),
          'WORKDIR /app',
          ...(pm === 'pnpm' || pm === 'yarn' ? ['RUN corepack enable'] : []),
          `COPY ${lockfiles(root).join(' ')} ./`,
          `RUN ${installCmd(pm, root)}`,
          ...(vendorPaths.length
            ? [
                "# Blade views Tailwind's @source lines scan; without them those classes are not compiled.",
                ...vendorPaths.map((v) => `COPY --from=vendor /app/${v} /app/${v}`),
              ]
            : []),
          'COPY . .',
          `RUN ${pm === 'npm' ? 'npm run' : `${pm} run`} build`,
          '',
        ]
      : []),
    `# Stage ${assets ? 3 : 2}: runtime`,
    `FROM serversideup/php:${minor}-${laravel ? 'frankenphp' : 'fpm-nginx'}`,
    ...(exts.length ? ['USER root', `RUN install-php-extensions ${exts.join(' ')}`, 'USER www-data'] : []),
    'WORKDIR /var/www/html',
    `ENV PHP_OPCACHE_ENABLE=1${laravel ? ' AUTORUN_ENABLED=true SSL_MODE=off' : ''}`,
    'COPY --chown=www-data:www-data . /var/www/html',
    'COPY --chown=www-data:www-data --from=vendor /app/vendor /var/www/html/vendor',
    ...(assets
      ? [
          mix
            ? 'COPY --chown=www-data:www-data --from=assets /app/public /var/www/html/public'
            : 'COPY --chown=www-data:www-data --from=assets /app/public/build /var/www/html/public/build',
        ]
      : []),
    ...(laravel ? ['RUN rm -f public/hot'] : []),
    ...(octane ? ['CMD ["php", "artisan", "octane:start", "--server=frankenphp", "--host=0.0.0.0", "--port=8080"]'] : []),
    'EXPOSE 8080',
    '',
  ].join('\n');
}

const DB_IMAGES = { postgres: 'postgres:17-alpine', mysql: 'mysql:8.4', mariadb: 'mariadb:11' } as const;

function dbService(ctx: Ctx, prod = false): { name: string; yaml: string[]; host: string; port: number; volume: string } | null {
  const db = ctx.stack.database;
  if (!db || db.engine === 'sqlite' || db.engine === 'unknown') return null;
  const e = ctx.env;
  const url = e.DATABASE_URL?.match(/^\w+:\/\/([^:@/]*)(?::([^@/]*))?@[^/]+\/([^?]+)/);
  const localUser = url?.[1] || e.DB_USERNAME || (db.engine === 'postgres' ? 'postgres' : 'app');
  const localPass = url?.[2] || e.DB_PASSWORD || 'secret';
  const localName = url?.[3] || e.DB_DATABASE || db.database || 'app';
  // Production: no secrets in the file; compose fills them from the platform's .env.
  const v = (key: string, local: string) => (prod ? `\${${key}}` : local);
  const name = v('DB_DATABASE', localName);
  const user = v('DB_USERNAME', localUser);
  const pass = v('DB_PASSWORD', localPass);
  if (db.engine === 'postgres') {
    return {
      name: 'db',
      host: 'db',
      port: 5432,
      volume: 'db-data',
      yaml: [
        '  db:',
        `    image: ${DB_IMAGES.postgres}`,
        '    environment:',
        `      POSTGRES_USER: ${JSON.stringify(user)}`,
        `      POSTGRES_PASSWORD: ${JSON.stringify(pass)}`,
        `      POSTGRES_DB: ${JSON.stringify(name)}`,
        '    volumes:',
        '      - db-data:/var/lib/postgresql/data',
        '    healthcheck:',
        '      test: ["CMD-SHELL", "pg_isready -U $$POSTGRES_USER -d $$POSTGRES_DB"]',
        '      interval: 5s',
        '      retries: 10',
      ],
    };
  }
  const maria = db.engine === 'mariadb';
  const root = localUser === 'root' && !prod;
  return {
    name: 'db',
    host: 'db',
    port: 3306,
    volume: 'db-data',
    yaml: [
      '  db:',
      `    image: ${maria ? DB_IMAGES.mariadb : DB_IMAGES.mysql}`,
      '    environment:',
      `      ${maria ? 'MARIADB' : 'MYSQL'}_ROOT_PASSWORD: ${JSON.stringify(prod ? '${DB_ROOT_PASSWORD:-${DB_PASSWORD}}' : pass)}`,
      `      ${maria ? 'MARIADB' : 'MYSQL'}_DATABASE: ${JSON.stringify(name)}`,
      ...(prod ? ['      # DB_USERNAME must not be "root" here; root uses DB_ROOT_PASSWORD (or DB_PASSWORD).'] : []),
      ...(root ? [] : [`      ${maria ? 'MARIADB' : 'MYSQL'}_USER: ${JSON.stringify(user)}`, `      ${maria ? 'MARIADB' : 'MYSQL'}_PASSWORD: ${JSON.stringify(pass)}`]),
      '    volumes:',
      '      - db-data:/var/lib/mysql',
      '    healthcheck:',
      maria
        ? '      test: ["CMD", "healthcheck.sh", "--connect", "--innodb_initialized"]'
        : '      test: ["CMD-SHELL", "mysqladmin ping -h 127.0.0.1 -p$$MYSQL_ROOT_PASSWORD"]',
      '      interval: 5s',
      '      retries: 10',
    ],
  };
}

const LOOPBACK = '(localhost|127\\.0\\.0\\.1|\\[::1\\])';

/**
 * The project's .env as seen from inside a container: app URLs → orb.local,
 * database/Redis hosts → the compose services, or → host.docker.internal when
 * they stay on this Mac (DBngin, Herd). `changed` holds only what differs.
 */
function dockerEnvMap(ctx: Ctx, project: string, db: ReturnType<typeof dbService>, redis: boolean) {
  const urlOf = (a: AppInfo) => `https://${serviceName(a, ctx.stack)}.${project}.orb.local`;
  const swaps: [RegExp, string][] = [];
  for (const a of servedApps(ctx.stack)) {
    for (const port of [a.port, a.configuredPort].filter((x): x is number => !!x)) {
      swaps.push([new RegExp(`https?://${LOOPBACK}:${port}\\b`, 'g'), urlOf(a)]);
    }
    if (a.domain) swaps.push([new RegExp(`https?://${a.domain.replace(/\./g, '\\.')}(:\\d+)?\\b`, 'g'), urlOf(a)]);
  }
  const set: Record<string, string> = { NODE_ENV: 'production' };
  const web = servedApps(ctx.stack).find((a) => a.kind === 'web') ?? servedApps(ctx.stack)[0];
  if (ctx.stack.runtime === 'php') {
    Object.assign(set, { APP_ENV: 'production', APP_DEBUG: 'false', LOG_CHANNEL: 'stderr', ...(web ? { APP_URL: urlOf(web) } : {}) });
  }
  const loop = new RegExp(`^${LOOPBACK}$`);
  const e = ctx.env;
  if (db) {
    if (e.DB_HOST !== undefined || ctx.stack.runtime === 'php') Object.assign(set, { DB_HOST: db.host, DB_PORT: String(db.port) });
  } else if (e.DB_HOST && loop.test(e.DB_HOST)) set.DB_HOST = 'host.docker.internal';
  if (redis) Object.assign(set, { REDIS_HOST: 'redis', REDIS_PORT: '6379' });
  else if (e.REDIS_HOST && loop.test(e.REDIS_HOST)) set.REDIS_HOST = 'host.docker.internal';

  const full: [string, string][] = [];
  const changed: Record<string, string> = {};
  const seen = new Set<string>();
  for (const [k, raw] of Object.entries(e)) {
    let v = raw;
    for (const [re, to] of swaps) v = v.replace(re, to);
    if (k === 'DATABASE_URL') {
      v = db
        ? v.replace(new RegExp(`@(${LOOPBACK.slice(1, -1)}|host\\.docker\\.internal)(:\\d+)?/`), `@${db.host}:${db.port}/`)
        : v.replace(new RegExp(`@${LOOPBACK}(:\\d+)?/`), '@host.docker.internal$2/');
    }
    if (k === 'REDIS_URL') {
      v = redis
        ? v.replace(new RegExp(`//([^@/]*@)?${LOOPBACK}(:\\d+)?`), '//$1redis:6379')
        : v.replace(new RegExp(`//([^@/]*@)?${LOOPBACK}`), '//$1host.docker.internal');
    }
    if (k in set) v = set[k];
    seen.add(k);
    full.push([k, v]);
    if (v !== raw) changed[k] = v;
  }
  for (const [k, v] of Object.entries(set)) if (!seen.has(k)) (full.push([k, v]), (changed[k] = v));
  const usesHost = Object.values(changed).some((v) => v.includes('host.docker.internal'));
  return { full, changed, usesHost };
}

const envLine = (k: string, v: string) => `${k}=${/[\s#"']/.test(v) ? JSON.stringify(v) : v}`;

function dockerEnvFile(map: ReturnType<typeof dockerEnvMap>): string {
  return [
    '# Generated by DevCatz from .env for docker compose (hosts = service names). Holds secrets: keep it out of git.',
    ...map.full.map(([k, v]) => envLine(k, v)),
    '',
  ].join('\n');
}

