/** Defaults for the generator's options, from the site's .env and settings. */
export function defaultOptions(p: ProjectConfig, stack: StackInfo, target: DockerTarget = 'local'): DockerGenOptions {
  const laravel = stack.apps.some((a) => a.framework === 'laravel');
  const scheduled = laravel && /Schedule::|->(daily|hourly|everyMinute|cron)\(/.test(readText(join(p.path, 'routes/console.php')) ?? '');
  return {
    target,
    // Production (Dokploy & co.): database and Redis are separate services, configured through env.
    withServices: target === 'local',
    // Off by default (user's choice): the queue worker container is added only when ticked.
    worker: false,
    scheduler: laravel && (Boolean(p.scheduler) || scheduled),
    split: false,
    // Production platforms (Dokploy) provide the .env; locally a generated .env.docker is the safe default.
    envFile: target === 'local' ? 'docker' : 'project',
    mrcatzDatatable: usesMrcatz(p.path, stack),
    dokployNetwork: target === 'production',
  };
}

