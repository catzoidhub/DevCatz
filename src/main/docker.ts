const appRoot = (a: AppInfo) => (isPhpFramework(a.framework) ? '/var/www/html' : '/app');

/** Production: an empty database file in its own folder of the image, owned by the user the app runs as. */
function withSqliteFolder(dockerfile: string, file: string, php: boolean): string {
  const lines = dockerfile.split('\n');
  const make = `mkdir -p /data/sqlite && touch /data/sqlite/${file}`;
  const add = php ? ['USER root', `RUN ${make} && chown -R www-data:www-data /data/sqlite`, 'USER www-data'] : [`RUN ${make}`];
  // Before the final stage's CMD / EXPOSE.
  const lastFrom = lines.map((l) => l.startsWith('FROM ')).lastIndexOf(true);
  let at = lines.findIndex((l, i) => i > lastFrom && /^(CMD|EXPOSE|ENTRYPOINT)\b/.test(l));
  if (at < 0) at = lines.length;
  lines.splice(at, 0, ...add);
  return lines.join('\n');
}

function laravelExtra(kind: 'worker' | 'scheduler', base: string[]): string[] {
  const cmd = kind === 'worker' ? '["php", "/var/www/html/artisan", "queue:work", "--tries=3", "--timeout=90"]' : '["php", "/var/www/html/artisan", "schedule:work"]';
  return [
    `  ${kind}:`,
    ...base,
    `    command: ${cmd}`,
    '    stop_signal: SIGTERM',
    '    healthcheck:',
    `      test: ["CMD", "healthcheck-${kind === 'worker' ? 'queue' : 'schedule'}"]`,
    '      start_period: 10s',
    '    restart: unless-stopped',
  ];
}

export function generate(
  input: GenerateInput,
  opts: DockerGenOptions,
): { files: DockerFile[]; composeFile: string; project: string; options: DockerGenOptions; mrcatzDetected: boolean } {
  const { p, stack } = input;
  const ctx: Ctx = {
    opts,
    p,
    stack,
    env: readEnvFiles(join(p.path, '.env')),
    phpVersion: input.phpVersion,
    goVersion: input.goVersion,
    pythonVersion: input.pythonVersion,
    nodeMajor: Number(input.nodeVersion?.replace(/^v/, '').split('.')[0]) || 22,
  };
  const local = opts.target === 'local';
  // A compose file already in use (e.g. the dev database) is left alone.
  const existingCompose = composeFiles(p.path).filter((c) => !c.generated);
  const composeFile = !local
    ? 'docker-compose.prod.yml'
    : existingCompose.some((c) => c.file === 'docker-compose.yml' || c.file === 'compose.yaml')
      ? 'docker-compose.local.yml'
      : 'docker-compose.yml';
  const project = projectName(p, composeFile);
  const apps = servedApps(stack);
  const files: { path: string; content: string }[] = [];
  const db = opts.withServices ? dbService(ctx, !local) : null;
  // Laravel's stock .env always has REDIS_HOST; only add Redis when a driver actually uses it.
  const e = ctx.env;
  const redis =
    opts.withServices &&
    (stack.runtime === 'php'
      ? [e.CACHE_STORE, e.CACHE_DRIVER, e.QUEUE_CONNECTION, e.SESSION_DRIVER, e.BROADCAST_CONNECTION].some((v) => v === 'redis')
      : Boolean(stack.redis?.client || e.REDIS_URL));
  if (opts.split && local) opts = { ...opts, split: false };
  // `.env.docker` (generated, hosts pointed at the containers) or the project's own .env.
  // Local + project .env: container-specific hosts/URLs go into `environment:`. Production + project .env: the
  // platform (Dokploy) writes that .env next to the compose file.
  const envMap = dockerEnvMap(ctx, project, db, redis);
  const projectEnv = opts.envFile === 'project';
  const rootEnvFile = projectEnv ? ['    env_file:', '      - path: .env', '        required: false'] : ['    env_file: .env.docker'];

  /** One block per service; written together, or one compose file each (`split`). */
  const blocks: { name: string; lines: string[]; volumes: string[] }[] = [];
  // Folder projects (frontend/ + backend/, TODO §29): every folder is a project of its own — its Dockerfile, build
  // context, .env and .dockerignore live in it; the compose file at the root runs one service per folder. A JS
  // workspace keeps the root as build context (its apps share the root lockfile and packages).
  const folders = stack.layout === 'folders';
  const dockerfileOf = (app: AppInfo, a: AppInfo) => (folders ? posix.join(app.dir, 'Dockerfile') : apps.length === 1 ? 'Dockerfile' : posix.join(a.dir === '.' ? '.' : a.dir, 'Dockerfile'));
  // Where each app answers inside the compose network (service name, container port) and the ports it uses on this
  // Mac: a variable of one app that points at another on 127.0.0.1 (API_INTERNAL_URL=http://127.0.0.1:8080) points
  // at that service instead (http://api:8080) — inside a container 127.0.0.1 is the container itself.
  const reach = apps.map((app) => {
    const sub = folders ? folderCtx(ctx, app) : null;
    const a = sub?.app ?? app;
    const env = sub?.ctx.env ?? ctx.env;
    const own = folders ? null : ownDockerfile(p.path, dockerfileOf(app, a));
    const hostPorts = new Set([a.port, a.configuredPort, ...a.portVars.map((v) => Number(env[v]) || null)].filter((x): x is number => !!x));
    return { app, svc: serviceName(app, stack), port: own?.port ?? portOf(a), hostPorts };
  });
  /** Production: what each service's .env still points at on this Mac (Catzoid, 2026-10-25). */
  const devLeft: string[] = [];
  const servicesLeft: string[] = [];
  const prodEnv = (app: AppInfo, svc: string, env: Record<string, string>) => {
    const lines: string[] = [];
    const left: string[] = [];
    const services: string[] = [];
    // Databases and other services: on the apps that talk to them (a shared root .env reaches the frontend too).
    const backends = apps.filter((x) => x.kind === 'api' || x.prisma || isPhpFramework(x.framework) || isPythonFramework(x.framework));
    const usesServices = !backends.length || backends.includes(app);
    for (const [k, v] of Object.entries(env)) {
      const m = v.match(/^(?:([a-z]+):\/\/)?(?:localhost|127\.0\.0\.1|\[::1\]):(\d+)(\/.*)?$/i);
      // Public addresses (the site's URL, CORS origins, OAuth callbacks) are the platform's, not a service name.
      const publicUrl = /SITE_URL|APP_URL|PUBLIC|ORIGIN|CORS|FRONTEND|CLIENT|BASE_URL|DOMAIN|REDIRECT|CALLBACK/.test(k);
      // Its own address: inside its own container 127.0.0.1:<port> is right.
      if (m && !publicUrl && reach.find((r) => r.app === app)?.hostPorts.has(Number(m[2]))) continue;
      const owner = m ? reach.find((r) => r.app !== app && r.hostPorts.has(Number(m[2]))) : undefined;
      if (m && owner && !publicUrl) {
        lines.push(`      # another app of this site: its service, never 127.0.0.1 (that is this container)`, `      ${k}: ${m[1] ? `${m[1]}://` : ''}${owner.svc}:${owner.port}${m[3] ?? ''}`);
        continue;
      }
      const loopback = new RegExp(`(^|[/@:])${LOOPBACK}([:/]|$)`).test(v);
      const service = /DATABASE|^DB_|REDIS|MONGO|POSTGRES|MYSQL|MARIADB|ELASTIC|OPENSEARCH|MEILI|TYPESENSE|^S3_|MINIO|AWS_ENDPOINT|SMTP|MAIL_HOST|AMQP|RABBIT|NATS|KAFKA/.test(k);
      if (service && !usesServices) continue;
      // A database / Redis / mail … on this Mac: in production it is a service of the platform with its own URL.
      if (loopback && service && !db) {
        services.push(k);
        continue;
      }
      if (loopback || /\.localhost\b/.test(v)) left.push(k);
    }
    if (left.length) devLeft.push(`${svc}: ${left.join(', ')}`);
    if (services.length) servicesLeft.push(`${svc}: ${services.join(', ')}`);
    return { lines };
  };
  for (const app of apps) {
    const svc = serviceName(app, stack);
    const sub = folders ? folderCtx(ctx, app) : null;
    const actx = sub?.ctx ?? ctx;
    const a = sub?.app ?? app;
    const at = (path: string) => (folders ? posix.join(app.dir, path) : path);
    const dockerfile = dockerfileOf(app, a);
    const php = isPhpFramework(a.framework);
    const sqlite = sqliteOf(actx, a);
    let content = a.framework === 'go' ? goDockerfile(actx, a) : php ? phpDockerfile(actx, a) : isPythonFramework(a.framework) ? pythonDockerfile(actx, a) : jsDockerfile(actx, a);
    if (sqlite && !local) content = withSqliteFolder(content, sqlite.file, php);
    if (folders) content = content.replace('Build context: the project root.', `Build context: this folder (${app.dir}/), as docker-compose.yml at the project root builds it.`);
    files.push({ path: dockerfile, content });
    // The project's own Dockerfile stays (it is only replaced when ticked): build it the way it expects.
    const own = folders ? null : ownDockerfile(actx.p.path, dockerfile);
    if (folders) files.push({ path: at('.dockerignore'), content: DOCKERIGNORE });
    // The folder's own .env (URLs of the other apps still point at their containers).
    const folderEnv = sub ? dockerEnvMap({ ...ctx, env: sub.ctx.env }, project, db, redis) : null;
    const appEnvMap = folderEnv ?? envMap;
    const envFile = !folders
      ? rootEnvFile
      : projectEnv
        ? ['    env_file:', `      - path: ./${at('.env')}`, '        required: false']
        : [`    env_file: ${at('.env.docker')}`];
    if (folders && !projectEnv) files.push({ path: at('.env.docker'), content: dockerEnvFile(appEnvMap) });
    const overrides = projectEnv && local ? Object.entries(appEnvMap.changed).map(([k, v]) => `      ${k}: ${JSON.stringify(v).replace(/\$/g, '$$$$')}`) : [];
    const prod = local ? null : prodEnv(app, svc, sub?.ctx.env ?? ctx.env);
    const hostGateway = local && appEnvMap.usesHost ? ['    extra_hosts:', '      - "host.docker.internal:host-gateway"'] : [];
    const port = own?.port ?? portOf(a);
    const deps = [...(db ? ['db'] : []), ...(redis ? ['redis'] : [])];
    const dependsOn = deps.length ? ['    depends_on:', ...deps.map((d) => `      ${d}:\n        condition: service_${d === 'db' ? 'healthy' : 'started'}`)] : [];
    const laravel = a.framework === 'laravel';
    const octane = laravel && usesOctane(actx.p.path);
    // Dokploy routes domains through Traefik on its external network.
    const network = !local && opts.dokployNetwork ? ['    networks:', '      - dokploy-network'] : [];
    // Uploads, logs and sessions survive rebuilds; the worker and scheduler share them.
    // SQLite: local = the Mac's file (its folder, or the file itself at the project root); production = its own volume.
    const inImage = sqlite ? (local ? posix.join(appRoot(a), sqlite.dir, sqlite.file) : `/data/sqlite/${sqlite.file}`) : null;
    const sqliteMount = !sqlite
      ? []
      : local
        ? [sqlite.dir === '.' ? `      - ./${at(sqlite.file)}:${posix.join(appRoot(a), sqlite.file)}` : `      - ./${at(sqlite.dir)}:${posix.join(appRoot(a), sqlite.dir)}`]
        : ['      - sqlite-data:/data/sqlite'];
    const sqliteEnv = sqlite?.key && inImage ? [`      ${sqlite.key}: ${JSON.stringify(sqlite.value(inImage))}`] : [];
    // Go: the uploads/ folder the Dockerfile creates survives rebuilds; local `replace` checkouts as extra build contexts.
    const goDir = a.framework === 'go' ? join(actx.p.path, a.dir) : null;
    const goUploads = goDir !== null && existsSync(join(goDir, 'uploads'));
    const extraContexts = goDir
      ? goLocalReplaces(goDir).map((r) => {
          const rel = posix.normalize(posix.join(app.dir, r.rel));
          return `        ${r.name}: ${rel.startsWith('..') ? rel : `./${rel}`}`;
        })
      : [];
    const mounts = [...(laravel ? ['      - app-storage:/var/www/html/storage'] : []), ...(goUploads ? [`      - ${svc}-uploads:/app/uploads`] : []), ...sqliteMount];
    const storage = mounts.length ? ['    volumes:', ...mounts] : [];
    const named = [...(laravel ? ['app-storage'] : []), ...(goUploads ? [`${svc}-uploads`] : []), ...(sqlite && !local ? ['sqlite-data'] : [])];
    const build = [
      '    build:',
      `      context: ${folders ? `./${app.dir}` : own && own.context !== '.' ? `./${own.context}` : '.'}`,
      `      dockerfile: ${folders ? 'Dockerfile' : own && own.context !== '.' ? posix.relative(own.context, dockerfile) : dockerfile}`,
      ...(extraContexts.length ? ['      additional_contexts:', ...extraContexts] : []),
      ...envFile,
      ...hostGateway,
      ...network,
      ...storage,
    ];
    blocks.push({ name: svc, volumes: named, lines: [
      `  ${svc}:`,
      ...build,
      '    environment:',
      // Hosts/URLs that differ inside the container (project .env mode).
      ...overrides,
      // The SQLite file at its path inside the container.
      ...sqliteEnv,
      ...(laravel
        ? [
            '      PHP_OPCACHE_ENABLE: "1"',
            '      AUTORUN_ENABLED: "true"',
            '      AUTORUN_LARAVEL_MIGRATION: "true"',
            '      AUTORUN_LARAVEL_MIGRATION_ISOLATION: "false"',
            '      AUTORUN_LARAVEL_STORAGE_LINK: "false"',
            '      SSL_MODE: "off"',
            ...(octane ? ['      OCTANE_SERVER: "frankenphp"'] : []),
          ]
        : []),
      // The app's own port variables point at the container port.
      ...[...new Set(['PORT', ...a.portVars])].map((v) => `      ${v}: "${port}"`),
      // Production: the other apps of the site by service name.
      ...(prod?.lines ?? []),
      ...(local
        ? [
            // OrbStack: https://<service>.<project>.orb.local; other engines: this localhost port.
            '    ports:',
            `      - "127.0.0.1:${input.hostPort(svc)}:${port}"`,
            '    labels:',
            `      dev.orbstack.http-port: "${port}"`,
          ]
        : [`    expose:`, `      - "${port}"`]),
      ...(octane ? ['    healthcheck:', '      test: ["CMD", "healthcheck-octane"]', '      start_period: 10s'] : []),
      ...(opts.split ? [] : dependsOn),
      '    restart: unless-stopped',
    ] });
    if (a.framework === 'laravel') {
      // Migrations run once, in the web container (serversideup's AUTORUN).
      const extraBase = [...build, '    environment:', ...overrides, ...sqliteEnv, '      AUTORUN_ENABLED: "false"', ...(opts.split ? [] : dependsOn)];
      if (opts.worker) blocks.push({ name: 'worker', volumes: named, lines: laravelExtra('worker', extraBase) });
      if (opts.scheduler) blocks.push({ name: 'scheduler', volumes: named, lines: laravelExtra('scheduler', extraBase) });
    }
  }
  const dataNet = !local && opts.dokployNetwork ? ['    networks:', '      - dokploy-network'] : [];
  if (db) blocks.push({ name: 'db', lines: [...db.yaml, ...dataNet], volumes: [db.volume] });
  if (redis) blocks.push({ name: 'redis', lines: ['  redis:', '    image: redis:7-alpine', '    volumes:', '      - redis-data:/data', ...dataNet], volumes: ['redis-data'] });
  const header = local
    ? [
        `${GENERATED_MARK}. Up: docker compose -f ${composeFile} -p ${project} up -d --build`,
        `# OrbStack serves each service at https://<service>.${project}.orb.local; with other engines use the published 127.0.0.1 ports.`,
      ]
    : [
        `${GENERATED_MARK} for production (Dokploy, Coolify, …): set this as the compose path.`,
        '# Database, Redis, APP_KEY, APP_URL, … come from the environment the platform writes to .env;',
        '# attach the domain to the web service on its exposed port.',
        ...(devLeft.length
          ? ['#', '# Set on the platform — .env still has this Mac\'s dev values (localhost, 127.0.0.1, *.localhost):', ...devLeft.map((l) => `#   ${l}`)]
          : []),
        ...(servicesLeft.length
          ? ['#', "# Point these at the platform's database / Redis / … services (their internal URL; .env has this Mac's):", ...servicesLeft.map((l) => `#   ${l}`)]
          : []),
      ];
  const render = (head: string[], bs: typeof blocks) => {
    const volumes = [...new Set(bs.flatMap((b) => b.volumes))];
    return [
      ...head,
      'services:',
      ...bs.flatMap((b) => b.lines),
      ...(volumes.length ? ['volumes:', ...volumes.map((v) => `  ${v}:`)] : []),
      ...(!local && opts.dokployNetwork ? ['networks:', '  dokploy-network:', '    external: true'] : []),
      '',
    ].join('\n');
  };
  const composePaths: string[] = [];
  if (opts.split) {
    // One stack per service (deployed separately on Dokploy); they reach each other through hosts set in env.
    for (const b of blocks) {
      const path = `docker-compose.${b.name}.yml`;
      composePaths.push(path);
      files.push({
        path,
        content: render(
          [
            `${GENERATED_MARK}: the "${b.name}" service on its own (one Dokploy/Coolify compose service per file).`,
            ...(b.name === 'db' || b.name === 'redis'
              ? [`# Point the app at it through env (${b.name === 'db' ? 'DB_HOST / DATABASE_URL' : 'REDIS_HOST / REDIS_URL'}) using the host the platform gives this service.`]
              : ['# Database, Redis, APP_KEY, APP_URL, … come from the environment the platform writes to .env.']),
          ],
          [b],
        ),
      });
    }
  } else {
    composePaths.push(composeFile);
    files.push({ path: composeFile, content: render(header, blocks) });
  }
  if (!folders) files.push({ path: '.dockerignore', content: DOCKERIGNORE });
  if (!projectEnv && !folders) files.push({ path: '.env.docker', content: dockerEnvFile(envMap) });

  return {
    composeFile: composePaths[0],
    project: projectName(p, composePaths[0]),
    options: opts,
    mrcatzDetected: usesMrcatz(p.path, stack),
    files: files.map((f) => {
      const abs = join(p.path, f.path);
      const current = existsSync(abs) ? readFileSync(abs, 'utf8') : null;
      return { ...f, current, same: current === f.content };
    }),
  };
}

/** Writes the chosen files; anything that exists must be listed in `overwrite`. */
export function writeFiles(root: string, files: { path: string; content: string }[], overwrite: string[]): string[] {
  const written: string[] = [];
  for (const f of files) {
    if (f.path.includes('..') || f.path.startsWith('/')) throw new Error(`Refusing to write ${f.path}`);
    const abs = join(root, f.path);
    if (existsSync(abs) && !overwrite.includes(f.path)) continue;
    mkdirSync(dirname(abs), { recursive: true });
    writeFileSync(abs, f.content);
    written.push(f.path);
  }
  // .env.docker holds secrets copied from .env.
  const gi = join(root, '.gitignore');
  if (written.includes('.env.docker') && existsSync(gi) && !/^\.env\.docker$/m.test(readFileSync(gi, 'utf8'))) {
    writeFileSync(gi, readFileSync(gi, 'utf8').replace(/\n?$/, '\n') + '.env.docker\n');
  }
  return written;
}

