/**
 * A site on SQLite (TODO §3): where its database file is, and how the containers reach it.
 * - Local: the Mac's own file is mounted (its folder, so SQLite's journal works), so a local test runs on the same
 *   data as the dev site.
 * - Production: a volume holding only the database (never over `database/`, which holds the migrations and would
 *   hide the ones of later builds), created empty in the image so the first migration fills it.
 * Laravel & co. (DB_CONNECTION=sqlite, DB_DATABASE), Prisma (`DATABASE_URL=file:./dev.db`), SQLAlchemy
 * (`sqlite:///app.db`) and Django's `db.sqlite3`.
 */
interface SqliteDb {
  /** Folder of the file, relative to the project ('.' = its root). */
  dir: string;
  file: string;
  /** The env variable that names the file, and its value for a path inside the container. */
  key: string | null;
  value: (path: string) => string;
}
function sqliteOf(ctx: Ctx, a: AppInfo): SqliteDb | null {
  if (a.dir !== '.') return null;
  const e = ctx.env;
  const root = ctx.p.path;
  const inside = (abs: string) => {
    const rel = relative(root, abs);
    return rel && !rel.startsWith('..') && !isAbsolute(rel) ? rel : null;
  };
  const split = (rel: string) => ({ dir: posix.dirname(rel.split('\\').join('/')), file: posix.basename(rel) });
  if ((e.DB_CONNECTION ?? '').toLowerCase() === 'sqlite') {
    const raw = e.DB_DATABASE || 'database/database.sqlite';
    const rel = isAbsolute(raw) ? inside(raw) : raw.replace(/^\.\//, '');
    return rel ? { ...split(rel), key: 'DB_DATABASE', value: (path) => path } : null;
  }
  const url = e.DATABASE_URL ?? '';
  if (url.startsWith('file:')) {
    // Prisma resolves it next to the schema (prisma/schema.prisma).
    const raw = url.slice(5).replace(/\?.*$/, '');
    const base = existsSync(join(root, 'prisma', 'schema.prisma')) ? 'prisma' : '.';
    const rel = isAbsolute(raw) ? inside(raw) : posix.normalize(posix.join(base, raw));
    return rel && !rel.startsWith('..') ? { ...split(rel), key: 'DATABASE_URL', value: (path) => `file:${path}` } : null;
  }
  const sa = url.match(/^sqlite(?:\+\w+)?:\/\/\/(.+)$/);
  if (sa) {
    const rel = sa[1].startsWith('/') ? inside(sa[1]) : sa[1].replace(/^\.\//, '');
    return rel ? { ...split(rel), key: 'DATABASE_URL', value: (path) => `sqlite:///${path}` } : null;
  }
  if (a.framework === 'django' && existsSync(join(root, 'db.sqlite3'))) return { dir: '.', file: 'db.sqlite3', key: null, value: (path) => path };
  return null;
}

/**
 * The project's own Dockerfile at `path` (not one DevCatz generated — those are never overwritten silently, so the
 * compose file builds whatever is there): the build context it expects and the port its last stage exposes.
 * Context: its own folder when the files it COPYs are there and not at the project root (a Go API's
 * `COPY go.mod go.sum ./` in apps/api), else the project root.
 */
function ownDockerfile(root: string, path: string): { context: string; port: number | null } | null {
  const text = readText(join(root, path));
  if (text === null || text.startsWith(GENERATED_MARK) || text.startsWith('# Generated by MrCatz Herd')) return null;
  const dir = posix.dirname(path);
  let atRoot = 0;
  let atDir = 0;
  for (const m of text.matchAll(/^\s*(?:COPY|ADD)\s+(.+)$/gim)) {
    const args = m[1].trim().split(/\s+/);
    if (args.some((x) => x.startsWith('--from='))) continue;
    const srcs = args.filter((x) => !x.startsWith('--')).slice(0, -1).filter((x) => x !== '.' && !/[*?[\]$]/.test(x));
    for (const src of srcs) {
      if (existsSync(join(root, src))) atRoot++;
      if (dir !== '.' && existsSync(join(root, dir, src))) atDir++;
    }
  }
  const lastStage = text.slice(Math.max(0, text.search(/^FROM[^\n]*$(?![\s\S]*^FROM)/m)));
  const exposed = [...lastStage.matchAll(/^\s*EXPOSE\s+(\d+)/gm)].pop()?.[1];
  return { context: atDir > atRoot ? dir : '.', port: exposed ? Number(exposed) : null };
}

/** A folder project's app seen as a project of its own (its folder as the root): for its Dockerfile and .env. */
function folderCtx(ctx: Ctx, app: AppInfo): { ctx: Ctx; app: AppInfo } {
  const path = join(ctx.p.path, app.dir);
  const stack = detectStack(path, ctx.p.domain);
  const own = servedApps(stack)[0];
  return { ctx: { ...ctx, p: { ...ctx.p, path }, stack, env: readEnvFiles(join(path, '.env')) }, app: own ? { ...own, dir: '.' } : { ...app, dir: '.' } };
}

