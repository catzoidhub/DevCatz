/**
 * Docker per site: generates a production-like Dockerfile + compose file for
 * the detected stack, then builds/runs it with `docker compose` on whatever
 * engine is running (OrbStack, Docker Desktop, Colima, Rancher Desktop,
 * Podman, Finch). OrbStack adds `https://<service>.<project>.orb.local`;
 * elsewhere the generated compose file publishes each app on 127.0.0.1.
 */

const COMPOSE_NAMES = /^(docker-)?compose(\.[\w-]+)?\.ya?ml$/;
const GENERATED_MARK = '# Generated by DevCatz';

interface EngineDef {
  id: DockerEngineId;
  name: string;
  /** App bundle in /Applications or ~/Applications. */
  app?: string;
  /** Windows: the app's .exe (`%ProgramFiles%` / `%LOCALAPPDATA%` placeholders); engines without one are macOS-only. */
  win?: string;
  macOnly?: boolean;
  /** CLI that, when found on PATH, means it is installed (Colima, Podman, Finch). */
  bin?: string;
  download: string;
}

/** Most recommended first (the "not installed" card offers them in this order). */
export const ENGINES: EngineDef[] = ([
  { id: 'orbstack', name: 'OrbStack', app: 'OrbStack.app', macOnly: true, download: 'https://orbstack.dev/download' },
  { id: 'docker-desktop', name: 'Docker Desktop', app: 'Docker.app', win: '%ProgramFiles%\\Docker\\Docker\\Docker Desktop.exe', download: 'https://www.docker.com/products/docker-desktop/' },
  { id: 'colima', name: 'Colima', bin: 'colima', macOnly: true, download: 'https://github.com/abiosoft/colima#installation' },
  { id: 'rancher', name: 'Rancher Desktop', app: 'Rancher Desktop.app', win: '%LOCALAPPDATA%\\Programs\\Rancher Desktop\\Rancher Desktop.exe', download: 'https://rancherdesktop.io/' },
  { id: 'podman', name: 'Podman', app: 'Podman Desktop.app', win: '%LOCALAPPDATA%\\Programs\\Podman Desktop\\Podman Desktop.exe', bin: 'podman', download: 'https://podman-desktop.io/downloads' },
  { id: 'finch', name: 'Finch', bin: 'finch', macOnly: true, download: 'https://github.com/runfinch/finch/releases' },
] as EngineDef[]).filter((e) => !(isWin && e.macOnly));

/** Windows: an engine's .exe with %ProgramFiles% / %LOCALAPPDATA% filled in. */
const winExe = (e: EngineDef) => e.win?.replace(/%(\w+)%/g, (_m, k: string) => process.env[k] ?? '');

const appInstalled = (app: string) => existsSync(join('/Applications', app)) || existsSync(join(homedir(), 'Applications', app));
const engineAppInstalled = (e: EngineDef) => (isWin ? !!winExe(e) && existsSync(winExe(e)!) : !!e.app && appInstalled(e.app));

const onPath = (bin: string): Promise<boolean> => hasCommand(bin);

/** The CLI that talks to the running engine: `docker` (most), `podman` or `finch`. */
let cli: { bin: string; compose: string[] } = { bin: 'docker', compose: ['compose'] };
/** The container CLI dockerStatus() found last (docker, podman or finch). */
export const dockerBin = () => cli.bin;
/** The compose command of that CLI: e.g. ['docker', 'compose']. */
export const dockerCompose = (): string[] => [cli.bin, ...cli.compose];
/** OrbStack answers: containers get `<service>.<project>.orb.local`. */
let orbLocal = false;

function engineFromDocker(context: string, endpoint: string, os: string): DockerEngineId {
  const s = `${context} ${endpoint} ${os}`.toLowerCase();
  if (s.includes('orbstack')) return 'orbstack';
  if (s.includes('colima')) return 'colima';
  if (s.includes('rancher') || s.includes('.rd/')) return 'rancher';
  if (s.includes('podman')) return 'podman';
  if (s.includes('docker desktop') || context === 'desktop-linux') return 'docker-desktop';
  return 'other';
}

export async function dockerStatus(): Promise<DockerStatus> {
  const installed = (
    await Promise.all(ENGINES.map(async (e) => (engineAppInstalled(e) || (e.bin && (await onPath(e.bin))) ? e : null)))
  ).filter((e): e is EngineDef => !!e);
  const base = { installed: installed.map((e) => e.id), cliFound: false, context: null, engine: null, orbLocal: false };

  let dockerError: string | null = null;
  if (await onPath('docker')) {
    const ctx = (await run('docker', ['context', 'show'], { timeout: 5000 })).stdout.trim();
    const endpoint = (await run('docker', ['context', 'inspect', ctx, '--format', '{{.Endpoints.docker.Host}}'], { timeout: 5000 })).stdout.trim();
    const info = await run('docker', ['info', '--format', '{{.OperatingSystem}}'], { timeout: 8000 });
    if (info.code === 0) {
      cli = { bin: 'docker', compose: ['compose'] };
      const engine = engineFromDocker(ctx, endpoint, info.stdout.trim());
      orbLocal = engine === 'orbstack';
      return { ...base, cliFound: true, daemon: true, context: ctx || null, engine, orbLocal: engine === 'orbstack', error: null };
    }
    // The docker CLI is there but its engine is down; Podman/Finch may still be up below.
    dockerError = info.stderr.trim().split('\n').pop() || 'The Docker engine is not running';
    Object.assign(base, { cliFound: true, context: ctx || null });
  }
  for (const [bin, id] of [['podman', 'podman'], ['finch', 'finch']] as const) {
    if (!(await onPath(bin))) continue;
    if ((await run(bin, ['info'], { timeout: 8000 })).code === 0) {
      cli = { bin, compose: ['compose'] };
      orbLocal = false;
      return { ...base, cliFound: true, daemon: true, engine: id, orbLocal: false, error: null };
    }
  }
  return { ...base, daemon: false, error: dockerError ?? (installed.length ? 'No container engine is running' : 'No container engine installed') };
}

/** Starts an installed engine: opens its app, or `colima start` / `podman machine start` / `finch vm start`. */
export async function startEngine(id: DockerEngineId): Promise<void> {
  const e = ENGINES.find((x) => x.id === id);
  if (!e) throw new Error(`Unknown engine ${id}`);
  if (engineAppInstalled(e)) {
    if (isWin) spawn(winExe(e)!, [], { detached: true, stdio: 'ignore', windowsHide: false }).unref();
    else await run('open', ['-a', e.app!.replace(/\.app$/, '')]);
    return;
  }
  const cmd: Record<string, string[]> = { colima: ['colima', 'start'], podman: ['podman', 'machine', 'start'], finch: ['finch', 'vm', 'start'] };
  const c = cmd[id];
  if (!c) throw new Error(`${e.name} is not installed`);
  const r = await run(c[0], c.slice(1), { timeout: 300_000 });
  if (r.code !== 0) throw new Error(`${c.join(' ')}: ${(r.stderr || r.stdout).trim().split('\n').pop()}`);
}

/** Compose files in the project root; `build: true` when one builds images of the app itself. */
export function composeFiles(root: string): { file: string; build: boolean; generated: boolean }[] {
  let names: string[] = [];
  try {
    names = readdirSync(root).filter((n) => COMPOSE_NAMES.test(n));
  } catch {
    return [];
  }
  return names
    .map((file) => {
      const text = readFileSync(join(root, file), 'utf8');
      return { file, build: /^\s+build:/m.test(text), generated: text.startsWith(GENERATED_MARK) || text.startsWith('# Generated by MrCatz Herd') };
    })
    .sort((a, b) => Number(b.build) - Number(a.build) || a.file.localeCompare(b.file));
}

/** Compose project name: generated files use the site slug (prod files get `-prod`, apart from a dev compose). */
export function projectName(p: ProjectConfig, file: string): string {
  // A worktree (feat-login.shop.localhost) must not share its parent's or another site's containers: feat-login-shop.
  const base = slugify((p.worktreeOf ? p.domain.replace(/\.[^.]+$/, '') : p.domain.split('.')[0]) || p.name);
  const m = file.match(/compose\.([\w-]+)\.ya?ml$/);
  return m ? `${base}-${m[1]}` : base;
}

